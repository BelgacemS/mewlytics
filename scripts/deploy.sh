#!/usr/bin/env bash
# Deploy the application to the local cluster.
#
#   scripts/deploy.sh local                 images from Docker Hub, tags set in k8s/overlays/local
#   scripts/deploy.sh local --dev <svc>...  also build <svc> inside minikube and deploy that build
#
# --dev records the built tag in k8s/overlays/dev/ (not versioned), an overlay on
# top of local. Services built earlier keep their dev build, unless its image is
# no longer in the cluster (after `minikube delete`): they then go back to Docker Hub.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
PROFILE="${MINIKUBE_PROFILE:-minikube}"
REGISTRY_USER="${DOCKERHUB_USERNAME:-belgacems}"
NAMESPACE=mewlytics
DEV_DIR="$ROOT/k8s/overlays/dev"

die() {
  echo "error: $*" >&2
  exit 1
}

usage() {
  echo "usage: $0 local [--dev <svc>]..." >&2
  exit 1
}

# Unique per commit, and per build when the tree has uncommitted changes, so
# that each build changes the pod spec and triggers a rollout.
dev_tag() {
  local tag
  tag="dev-$(git -C "$ROOT" rev-parse --short HEAD)"
  if [[ -n "$(git -C "$ROOT" status --porcelain)" ]]; then
    tag="$tag-$(date +%s)"
  fi
  echo "$tag"
}

build_dev_image() {
  local svc="$1" tag="$2"
  [[ -f "$ROOT/services/$svc/Dockerfile" ]] || die "no Dockerfile for service '$svc'"
  # Built from the repository root: the workspace lockfile lives there.
  (cd "$ROOT" && minikube -p "$PROFILE" image build \
    -t "docker.io/$REGISTRY_USER/mewlytics-$svc:$tag" \
    -f "services/$svc/Dockerfile" .)
  mkdir -p "$DEV_DIR/tags"
  echo "$tag" >"$DEV_DIR/tags/$svc"
}

# Drop the dev tags whose image is gone, which would otherwise end in ImagePullBackOff.
prune_dev_tags() {
  local images file svc
  images="$(minikube -p "$PROFILE" image ls --format short)"
  for file in "$DEV_DIR"/tags/*; do
    svc="$(basename "$file")"
    if ! grep -qxF "docker.io/$REGISTRY_USER/mewlytics-$svc:$(<"$file")" <<<"$images"; then
      echo "warning: dev image of $svc not in the cluster, using Docker Hub" >&2
      rm "$file"
    fi
  done
}

# Rewritten from tags/ on each run, which keeps the tags of the other services.
write_dev_overlay() {
  local file svc
  for file in "$DEV_DIR"/tags/*; do
    echo "dev build: $(basename "$file") $(<"$file")"
  done
  {
    echo "# Generated by scripts/deploy.sh, not versioned."
    echo "apiVersion: kustomize.config.k8s.io/v1beta1"
    echo "kind: Kustomization"
    echo "resources:"
    echo "  - ../local"
    echo "images:"
    for file in "$DEV_DIR"/tags/*; do
      svc="$(basename "$file")"
      echo "  - name: docker.io/$REGISTRY_USER/mewlytics-$svc"
      echo "    newTag: $(<"$file")"
    done
  } >"$DEV_DIR/kustomization.yaml"
}

main() {
  [[ "${1:-}" == local ]] || usage
  shift

  local -a dev_services=()
  while (($#)); do
    case "$1" in
      --dev)
        [[ -n "${2:-}" ]] || usage
        dev_services+=("$2")
        shift 2
        ;;
      *) usage ;;
    esac
  done

  # Always target the minikube context, whatever the current one is.
  local -a kube=(kubectl --context "$PROFILE")
  local overlay="$ROOT/k8s/overlays/local"

  if ((${#dev_services[@]})); then
    local svc tag
    tag="$(dev_tag)"
    for svc in "${dev_services[@]}"; do
      build_dev_image "$svc" "$tag"
    done
    prune_dev_tags
    write_dev_overlay
    overlay="$DEV_DIR"
  fi

  "${kube[@]}" apply -k "$overlay"
  # istiod creates the gateway Deployment from the Gateway object, possibly after
  # apply returns: without this wait, rollout status could skip it.
  "${kube[@]}" -n "$NAMESPACE" wait --for=create deploy/gateway-istio --timeout=60s
  "${kube[@]}" -n "$NAMESPACE" rollout status deploy --timeout=180s
  "${kube[@]}" -n "$NAMESPACE" get pods
}

main "$@"
